import '@angular/compiler';
import { strict as assert } from 'node:assert';
import { signal, provideZonelessChangeDetection } from '@angular/core';
import { DOCUMENT } from '@angular/common';
import { TestBed, TestComponentRenderer } from '@angular/core/testing';
import { BrowserDynamicTestingModule, platformBrowserDynamicTesting } from '@angular/platform-browser-dynamic/testing';
import { Subject } from 'rxjs';
import { CatalogService } from '../projects/customer-app/src/app/services/catalog.service';
import { CustomerCatalogApiService } from '../projects/customer-app/src/app/services/customer-catalog-api.service';
import { AuthService } from '../projects/customer-app/src/app/services/auth.service';

// Exercise the real service with explicitly ordered responses. No browser or production API is mocked.
TestBed.initTestEnvironment(BrowserDynamicTestingModule, platformBrowserDynamicTesting());
const requests: Record<string, Subject<any>[]> = {};
const api = Object.fromEntries(['getHome', 'getCategories', 'getVendors', 'getProducts', 'explore', 'vendorRecommendations', 'getVendor', 'getProduct'].map(name => [name, () => {
  const response = new Subject<any>();
  (requests[name] ||= []).push(response);
  return response;
}]));
const auth = { sessionVersion: 0, currentUser: signal(null), isLoggedIn: () => false };
TestBed.configureTestingModule({ providers: [provideZonelessChangeDetection(), {provide: DOCUMENT, useValue: {}}, {provide: TestComponentRenderer, useValue: {removeAllRootElements() {}}}, CatalogService, {provide: CustomerCatalogApiService, useValue: api}, {provide: AuthService, useValue: auth}] });
const catalog = TestBed.inject(CatalogService);
const vendor = { id: 'old-store', store_name: 'Previous area store', is_open: true, is_open_now: true, is_accepting_orders: true, is_serviceable: true };
const product = { id: 'old-product', name: 'Previous area product', price: '120', stock: 10, vendor };
const category = { id: 'old-category', name: 'Previous area category', is_active: true };
const finish = (method: string, value: any, index = 0) => { requests[method][index].next(value); requests[method][index].complete(); };

catalog.loadHome({lat: 12, lng: 77});
catalog.loadCategories({lat: 12, lng: 77});
catalog.loadStores({lat: 12, lng: 77});
catalog.loadProducts({lat: 12, lng: 77});
catalog.loadExplore({lat: 12, lng: 77});
catalog.loadBestDealRecommendations(vendor.id);
catalog.loadStoreProducts(vendor.id, {lat: 12, lng: 77});
catalog.ensureProductLoaded(product.id, {lat: 12, lng: 77});
catalog.clearDeliverableCatalog();
finish('getHome', {serviceability: {is_serviceable: true}, categories: [category], nearby_stores: [vendor], recommended_products: [product]});
finish('getCategories', [category]);
finish('getVendors', {results: [vendor], count: 1, next: '?page=2'});
finish('getProducts', {results: [product], count: 1, next: '?page=2'});
finish('explore', {products: [product], stores: [vendor], categories: [category], summary: {product_count: 1}, next_page: 2});
finish('vendorRecommendations', {products: [product]});
finish('getVendor', {...vendor, products: [product]});
finish('getProduct', product);
assert.equal(catalog.products().length, 0, 'Late product responses must not repopulate an unavailable area');
assert.equal(catalog.stores().length, 0, 'Late store responses must not repopulate an unavailable area');
assert.equal(catalog.collectionProducts().length, 0);
assert.equal(catalog.exploreResults().products.length, 0);
assert.equal(catalog.productsHasMore(), false);
assert.equal(catalog.exploreHasMore(), false);
assert.equal(catalog.storesHasMore(), false);
assert.equal(catalog.homeLoading(), false);
assert.equal(catalog.productsLoading(), false);
assert.equal(catalog.storesLoading(), false);
assert.equal(catalog.isStoreProductsLoading(vendor.id), false);
console.log('PASS: unavailable-area reset ignores all late catalog responses and settles loading/pagination.');

catalog.loadHome({lat: 0, lng: 0});
finish('getHome', {serviceability: {is_serviceable: false}, categories: [category]}, 1);
assert.equal(catalog.homeLoading(), false, 'Unavailable Home must finish its own loading state');
assert.equal(catalog.homeResolved(), true);
assert.equal(catalog.products().length, 0);
console.log('PASS: unavailable Home settles without a permanent skeleton.');

catalog.loadCategories({lat: 12, lng: 77});
catalog.loadCategories({lat: 13, lng: 78});
finish('getCategories', [{...category, id: 'new-category', name: 'Current area category'}], 2);
finish('getCategories', [category], 1);
assert.equal(catalog.categories()[1].id, 'new-category', 'Older category request must not replace the new location');
console.log('PASS: reversed category responses keep the current location result.');

catalog.loadStoreProducts(vendor.id, {lat: 12, lng: 77});
finish('getVendor', {...vendor, is_open_now: false, products: []}, 1);
assert.equal(catalog.getStoreDetail(vendor.id).raw?.is_open_now, false, 'Public closed-store details must remain visible');
assert.equal(catalog.isStoreProductsLoading(vendor.id), false);
console.log('PASS: resetting availability allows the same store/location to reload its closed-store detail.');

catalog.refreshSearch('apple', {lat: 12, lng: 77});
catalog.clearDeliverableCatalog();
finish('getProducts', [product], 1);
finish('getVendors', [vendor], 1);
assert.equal(catalog.products().length, 0);
assert.equal(catalog.stores().length, 0);
catalog.refreshSearch('apple', {lat: 13, lng: 78});
catalog.refreshSearch('');
finish('getProducts', [product], 2);
finish('getVendors', [vendor], 2);
assert.equal(catalog.products().length, 0);
console.log('PASS: cleared search and unavailable-area reset reject old suggestion responses.');

catalog.loadProducts({lat: 12, lng: 77});
catalog.loadStores({lat: 12, lng: 77});
catalog.loadExplore({lat: 12, lng: 77});
catalog.loadBestDealRecommendations(vendor.id);
auth.sessionVersion++;
finish('getProducts', [product], 3);
finish('getVendors', [vendor], 3);
finish('explore', {products: [product], stores: [vendor]}, 1);
finish('vendorRecommendations', {products: [product]}, 1);
assert.equal(catalog.products().length, 0);
assert.equal(catalog.stores().length, 0);
assert.equal(catalog.recommendedProducts().length, 0);
console.log('PASS: responses from an earlier authentication session are ignored.');

catalog.loadHome({lat: 14, lng: 79});
catalog.loadStoreProducts('closed-store', {lat: 14, lng: 79});
finish('getHome', {serviceability: {is_serviceable: false}}, 2);
finish('getVendor', {...vendor, id: 'closed-store', store_name: 'Current closed store', is_open: false, is_open_now: false, products: []}, 2);
assert.equal(catalog.getStoreDetail('closed-store').name, 'Current closed store', 'Unavailable Home must not discard a pending public closed-store detail');
assert.equal(catalog.products().length, 0);
assert.equal(catalog.stores().length, 0);
assert.equal(catalog.isStoreProductsLoading('closed-store'), false);
console.log('PASS: concurrent unavailable Home preserves current public closed-store metadata without restoring shopping inventory.');

catalog.loadStoreProducts('sequence-store', {lat: 14, lng: 79});
catalog.clearDeliverableCatalog();
catalog.loadStoreProducts('sequence-store', {lat: 14, lng: 79});
finish('getVendor', {...vendor, id: 'sequence-store', store_name: 'Old detail', products: []}, 3);
assert.equal(catalog.isStoreProductsLoading('sequence-store'), true, 'An old same-query response must not settle the replacement request');
finish('getVendor', {...vendor, id: 'sequence-store', store_name: 'Latest detail', products: []}, 4);
assert.equal(catalog.getStoreDetail('sequence-store').name, 'Latest detail');
assert.equal(catalog.isStoreProductsLoading('sequence-store'), false);
console.log('PASS: same-query store retries keep the latest detail and its loading state.');

catalog.loadProducts({lat: 14, lng: 79});
finish('getProducts', {results: [product], count: 1, next: '?page=2'}, 4);
catalog.loadExplore({lat: 14, lng: 79});
finish('explore', {products: [product], stores: [vendor], next_page: 2}, 2);
assert.equal(catalog.collectionProducts().length, 1);
assert.equal(catalog.exploreResults().products.length, 1);
catalog.clearDeliverableCatalog();
assert.equal(catalog.collectionProducts().length, 0);
assert.equal(catalog.exploreResults().products.length, 0);
assert.equal(catalog.collectionCount(), null);
assert.equal(catalog.productsHasMore(), false);
assert.equal(catalog.exploreHasMore(), false);
console.log('PASS: availability reset clears already loaded collections and pagination.');

catalog.loadHome({lat: 15, lng: 80});
catalog.loadStoreProducts('paused-public-store', {lat: 15, lng: 80});
finish('getVendor', {...vendor, id: 'paused-public-store', store_name: 'Paused public store', is_accepting_orders: false, is_open_now: false, products: [product]}, 5);
assert.equal(catalog.productsForStoreDetail('paused-public-store').length, 1);
finish('getHome', {serviceability: {is_serviceable: false}}, 3);
assert.equal(catalog.productsForStoreDetail('paused-public-store').length, 1, 'Unavailable Home arriving after public detail must preserve its browse-only product list');
assert.equal(catalog.getStoreDetail('paused-public-store').raw?.is_accepting_orders, false);
assert.equal(catalog.products().length, 0, 'Public products must not restore deliverable shopping inventory');
assert.equal(catalog.stores().length, 0);
catalog.loadStoreProducts('paused-public-store', {lat: 16, lng: 81});
finish('getVendor', {...vendor, id: 'paused-public-store', is_serviceable: false, products: []}, 6);
assert.equal(catalog.productsForStoreDetail('paused-public-store').length, 0, 'New unserviceable detail must replace the old public product list');
console.log('PASS: unavailable Home preserves an already loaded paused storefront; new-area detail replaces its products.');
TestBed.resetTestingModule();
